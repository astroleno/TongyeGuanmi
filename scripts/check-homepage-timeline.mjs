function read(relativePath) {
  return readFileSync(new URL(relativePath, root), 'utf8');
}

function parseAttributes(tag) {
  const attrs = new Map();
  const attrPattern = /\s([A-Za-z0-9:_-]+)(?:="([^"]*)")?/g;
  for (const match of tag.matchAll(attrPattern)) {
    attrs.set(match[1], match[2] ?? '');
  }
  return attrs;
}

const nodes = [...indexHtml.matchAll(/<([A-Za-z][A-Za-z0-9:-]*)\b[^>]*>/g)]
  .map((match) => ({
    tag: match[1].toLowerCase(),
    raw: match[0],
    index: match.index ?? -1,
    attrs: parseAttributes(match[0])
  }));

function hasClass(node, className) {
  return (node.attrs.get('class') || '').split(/\s+/).includes(className);
}

function matchesSelector(node, selector) {
  if (selector.startsWith('.')) {
    return hasClass(node, selector.slice(1));
  }

  if (selector.startsWith('#')) {
    return node.attrs.get('id') === selector.slice(1);
  }

  const attrMatch = selector.match(/^\[([A-Za-z0-9:_-]+)(?:="([^"]*)")?\]$/);
  if (attrMatch) {
    const [, name, value] = attrMatch;
    return value === undefined ? node.attrs.has(name) : node.attrs.get(name) === value;
  }

  return node.tag === selector.toLowerCase();
}

function findNodes(selector) {
  return nodes.filter((node) => matchesSelector(node, selector));
}

function assertUnique(values, label) {
  const duplicates = values.filter((value, index) => values.indexOf(value) !== index);
  assert.equal(duplicates.length, 0, `${label} must be unique; duplicates: ${[...new Set(duplicates)].join(', ')}`);
}

function assertRange(name, value) {
  assert.ok(Array.isArray(value), `${name} must be an array`);
  assert.equal(value.length, 2, `${name} must have exactly two entries`);
  assert.ok(value.every((entry) => Number.isFinite(entry)), `${name} entries must be finite numbers`);
  assert.ok(value[0] >= 0 && value[1] <= 1, `${name} must stay inside 0..1`);
  assert.ok(value[0] < value[1], `${name} must have start < end`);
}

function assertCloseEnough(actual, expected, message, epsilon = 0.0001) {
  assert.ok(actual <= expected + epsilon, message);
}

function getSectionEnd(sectionNode) {
  const closeIndex = indexHtml.indexOf('</section>', sectionNode.index);
  assert.ok(closeIndex > sectionNode.index, `Section ${sectionNode.attrs.get('id')} must have a closing tag`);
  return closeIndex;
}

