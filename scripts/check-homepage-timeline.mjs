const sceneIds = new Set(timelineScenes.map((scene) => scene.id));
const handoffIds = new Set(handoffs.map((handoff) => handoff.id));

for (const scene of timelineScenes) {
  const sceneNodes = findNodes(scene.sectionSelector || scene.sceneSelector);
  assert.ok(sceneNodes.length >= 1, `Timeline scene ${scene.id} selector must resolve`);
  if (scene.sectionSelector || scene.sceneSelector) {
    assert.equal(sceneNodes.length, 1, `Timeline scene ${scene.id} selector must resolve uniquely`);
  }

  const sectionNode = scene.sectionId ? sceneNodes[0] : null;
  const sectionEnd = sectionNode?.tag === 'section' ? getSectionEnd(sectionNode) : null;

  if (scene.role === 'target') {
    assert.ok(scene.sceneTarget, `Target scene ${scene.id} must declare sceneTarget`);
    assert.equal(sectionNode.attrs.get('data-scene-target'), scene.sceneTarget, `Target scene ${scene.id} section must declare data-scene-target`);
    assert.notEqual(
      sectionNode.attrs.get('data-entry-owner'),
      'timeline',
      `Target scene ${scene.id} must not put data-entry-owner on the whole section`
    );
  }

  for (const copy of scene.copySelectors || []) {
    const copyNodes = findNodes(copy.selector);
    assert.ok(copyNodes.length >= 1, `Timeline scene ${scene.id} copy selector ${copy.selector} must resolve`);
    if (copy.unique !== false && !copy.allowMany) {
      assert.equal(copyNodes.length, 1, `Timeline scene ${scene.id} copy selector ${copy.selector} must resolve uniquely`);
    }

    for (const copyNode of copyNodes) {
      if (sectionNode?.tag === 'section' && !scene.sourceOnly) {
        assert.ok(
          copyNode.index > sectionNode.index && copyNode.index < sectionEnd,
          `Timeline scene ${scene.id} copy selector ${copy.selector} must resolve inside its section`
        );
      }

      assert.equal(copyNode.attrs.get('data-scene-copy'), scene.id, `Timeline scene ${scene.id} copy must declare data-scene-copy`);
      if (scene.sceneTarget) {
        assert.equal(copyNode.attrs.get('data-scene-target'), scene.sceneTarget, `Timeline scene ${scene.id} copy must declare data-scene-target`);
      }
      if (copy.entryOwner) {
        assert.equal(copyNode.attrs.get('data-entry-owner'), copy.entryOwner, `Timeline scene ${scene.id} copy must declare data-entry-owner`);
        assert.equal(copyNode.attrs.get('data-entry-state'), 'pending', `Timeline scene ${scene.id} copy must start pending`);
      }
    }
  }
}

